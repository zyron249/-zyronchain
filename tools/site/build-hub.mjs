#!/usr/bin/env node
// Build step for the ZYRON HUB page (website/hub/index.html), with --check for CI:
//  1. renders the launch flags block from docs/l1-launch-authorization.json (static, build-time; the Hub never
//     reads launch state from a live source it does not control), and
//  2. content-versions the Hub's CSS/JS references (?v=<sha256[:12]>) like tools/site/stamp-site.mjs.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const site = join(repo, 'website');
const page = join(site, 'hub', 'index.html');
const check = process.argv.includes('--check');
const auth = JSON.parse(readFileSync(join(repo, 'docs', 'l1-launch-authorization.json'), 'utf8'));

export const FLAGS = [
  ['publicTestnetAuthorized', 'Public testnet authorized by governance'],
  ['publicTestnetActivationAllowed', 'Public testnet activation allowed'],
  ['mainnetAuthorized', 'Mainnet authorized by governance'],
  ['mainnetActivationAllowed', 'Mainnet activation allowed']
];
// Shown beside the mainnet authorization flag so 'Yes' is never read as 'mainnet is live'.
export const MAINNET_NOTICE = ' <strong class="state state-off hub-flag-notice">Mainnet is not live; activation is off</strong>';
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
export function renderFlags(a = auth) {
  const rows = FLAGS.map(([key, label]) => {
    if (typeof a[key] !== 'boolean') throw new Error(`authorization flag ${key} is not boolean`);
    return `        <div class="hub-row" data-flag="${key}"><dt>${esc(label)}</dt><dd><span class="state state-${a[key] ? 'ok' : 'off'}">${a[key] ? 'Yes' : 'No'}</span>${key === 'mainnetAuthorized' && a.mainnetActivationAllowed !== true ? MAINNET_NOTICE : ''}</dd></div>`;
  });
  const reqs = (list) => list.map((r) => `          <li><code>${esc(r)}</code></li>`).join('\n');
  return [
    '<!-- launch-flags:start (generated by tools/site/build-hub.mjs from docs/l1-launch-authorization.json) -->',
    `      <p class="hub-note">Source: <code>docs/l1-launch-authorization.json</code> · status <code>${esc(a.status)}</code>. Authorization does not waive readiness gates.</p>`,
    '      <dl class="hub-list">',
    ...rows,
    '      </dl>',
    `      <details class="hub-details"><summary>Open public testnet requirements (${a.publicTestnetActivationRequirements.length})</summary>`,
    '        <ul>',
    reqs(a.publicTestnetActivationRequirements),
    '        </ul></details>',
    `      <details class="hub-details"><summary>Open mainnet requirements (${a.mainnetActivationRequirements.length})</summary>`,
    '        <ul>',
    reqs(a.mainnetActivationRequirements),
    '        </ul></details>',
    '      <!-- launch-flags:end -->'
  ].join('\n');
}

const version = (rel) => createHash('sha256').update(readFileSync(join(site, rel))).digest('hex').slice(0, 12);
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const before = readFileSync(page, 'utf8');
  const after = before
    .replace(/<!-- launch-flags:start[\s\S]*?<!-- launch-flags:end -->/, renderFlags())
    .replace(/(href|src)="(\.\.\/|\.\/)([a-z0-9-]+\.(?:css|js))(?:\?v=[0-9a-f]{12})?"/g, (_, attr, pre, file) =>
      `${attr}="${pre}${file}?v=${version(pre === '../' ? file : `hub/${file}`)}"`);
  if (!after.includes('launch-flags:start')) throw new Error('hub page has no launch-flags block');
  if (after !== before) {
    if (check) { console.error('website/hub/index.html is stale; run node tools/site/build-hub.mjs'); process.exit(1); }
    writeFileSync(page, after);
    console.log('hub-build-written website/hub/index.html');
  }
  console.log(check ? 'hub-build-ok' : 'hub-build-done');
}
